<p>Forgeで販売するデジタル商品（WordPressテーマなど）の返金について定めます。</p>

<h2>1. 基本的な考え方</h2>
<p>デジタル商品は、ダウンロードした時点で内容を複製・利用できる性質があるため、お支払い後の返品・キャンセル・お客様のご都合による返金はお受けしていません。購入前に、各商品ページのデモサイトと説明をご確認ください。</p>

<h2>2. 返金する場合</h2>
<p>次のいずれかに当てはまる場合は、お支払い金額を返金します。</p>
<ul>
  <li><strong>二重のご請求・誤った金額のご請求</strong>があった場合</li>
  <li><strong>ダウンロードできない</strong>状態が続き、当社が解消できない場合</li>
  <li><strong>商品ページに記載した動作環境で、重大な不具合</strong>（テーマが有効化できない、主要な機能が動作しないなど）があり、購入から14日以内にご連絡をいただいたにもかかわらず、当社が修正版の提供や回避方法のご案内で解消できない場合</li>
  <li>その他、法令により返金が必要な場合</li>
</ul>

<h2>3. 返金できない場合</h2>
<ul>
  <li>お客様のご都合によるもの（イメージと違った、使わなくなった、制作の予定が変わったなど）</li>
  <li>お客様のサーバー環境、他のテーマ・プラグインとの組み合わせなど、当社の管理が及ばない原因による場合</li>
  <li>商品ページに記載のない機能や、個別のカスタマイズ・デザイン変更ができないことを理由とする場合</li>
  <li>利用規約に違反した場合</li>
</ul>

<h2>4. お申し出の方法</h2>
<p>購入時のメールアドレス、ご注文の内容、不具合の内容（発生した状況や画面の様子）を添えて、<a href="mailto:{{ config('forge.company.email') }}">{{ config('forge.company.email') }}</a> までご連絡ください。内容を確認のうえ、原則として3営業日以内に返信します。</p>

<h2>5. 返金の方法と時期</h2>
<p>返金は、お支払いに使われたクレジットカードへ、決済サービス Stripe を通じて行います。カード会社での反映時期は、ご利用のカード会社によって異なります（通常、数日から数週間かかります）。</p>

<h2>6. 返金後の取り扱い</h2>
<p>返金を行った場合、該当するライセンスは無効になり、商品のダウンロード・サポート・アップデートの提供は終了します。すでにご利用のサイトからは、テーマを取り除いてください。</p>
